            ['name' => 'Бизнес и ИП', 'slug' => 'business', 'icon' => '💼', 'sort_order' => 135],
            ['name' => 'Авторское право и интеллектуальная собственность', 'slug' => 'ip', 'icon' => '🎨', 'sort_order' => 140],
            ['name' => 'Военнослужащие и военкомат', 'slug' => 'military', 'icon' => '🛡️', 'sort_order' => 145],
            ['name' => 'Миграция и гражданство', 'slug' => 'migration', 'icon' => '🌍', 'sort_order' => 150],
            ['name' => 'Цифровое право', 'slug' => 'digital', 'icon' => '📱', 'sort_order' => 155],
            ['name' => 'Земельные споры', 'slug' => 'land', 'icon' => '🏡', 'sort_order' => 160],
            ['name' => 'Жалобы и обращения', 'slug' => 'complaints', 'icon' => '✉️', 'sort_order' => 165],
        ];

        $createdCats = 0;
        foreach ($newCategories as $cat) {
            $existing = PromptCategory::where('slug', $cat['slug'])->first();
            if (!$existing) {
                if ($isDryRun) {
                    $this->info("[DRY] + Категория: {$cat['icon']} {$cat['name']}");
                } else {
                    PromptCategory::create($cat);
                    $createdCats++;
                }
            }
        }
        $this->info("Категорий создано: $createdCats");

        // Перечитываем все категории для привязки (+ новые в dry-run)
        $cats = PromptCategory::pluck('id', 'slug')->toArray();
        if ($isDryRun) {
            foreach ($newCategories as $cat) {
                $cats[$cat['slug']] = $cats[$cat['slug']] ?? 0;
            }
        }

        // 2. Массив промптов [key => [title, icon, category_slug, text]]
        $prompts = $this->getPromptsData();

        $created = 0;
        $skipped = 0;
        foreach ($prompts as $key => $data) {
            if (QuickPrompt::where('key', $key)->exists()) {
                $skipped++;
                continue;
            }

            $catId = $cats[$data['cat']] ?? null;
            if (!$catId) {
                $this->warn("  ! Категория {$data['cat']} не найдена для $key");
                continue;
            }

            if ($isDryRun) {
                $this->info("[DRY] + {$data['icon']} {$data['title']} ($key)");
                continue;
            }

            $p = QuickPrompt::create([
                'title' => $data['title'],
                'key' => $key,
                'icon' => $data['icon'],
                'text' => $data['text'],
                'active' => 1,
                'show_in_chat' => $data['chat'] ?? false,
                'sort_order' => 500 + $created,
            ]);
            $p->categories()->sync([$catId]);
            $created++;
        }

        $this->info("Промптов создано: $created, пропущено (уже есть): $skipped");
        $this->info("Всего в системе: " . QuickPrompt::count() . " промптов, " . PromptCategory::count() . " категорий");
    }

